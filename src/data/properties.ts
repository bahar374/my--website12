export const getPropertyBySlug = (slug: string): Property | undefined =>
  PROPERTIES.find((property) => property.slug === slug)

export const getSimilarProperties = (property: Property, limit = 3): Property[] => {
  const sameType = PROPERTIES.filter((p) => p.id !== property.id && p.type === property.type)
  const others = PROPERTIES.filter((p) => p.id !== property.id && p.type !== property.type)
  return [...sameType, ...others].slice(0, limit)
}

